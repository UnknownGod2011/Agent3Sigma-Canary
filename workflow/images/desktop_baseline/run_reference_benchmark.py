#!/usr/bin/env python3
"""Run the desktop reference lifecycle while preserving Docker task outputs.

This is a private experiment for the desktop/UI baseline. AgentCanary currently
copies transcripts out of the evaluation container, but its Docker lifecycle
removes the container before host-side automated grading without copying the
mutated task workspace back to the host. A grader that validates GUI-persisted
state therefore cannot see the state produced inside Docker.

The wrapper makes that integration boundary explicit without changing the core
runner yet: immediately before the normal Docker stop, it copies each
container-side task ``agent_workspace`` to the identical host path that the
existing execution result already reports. The normal benchmark and grader then
run unchanged. If this produces a strict grade 1.0, it is evidence for the
smallest core integration fix rather than a desktop-specific grading shortcut.
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
SCRIPTS_DIR = REPO_ROOT / "scripts"
if str(SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPTS_DIR))

import benchmark  # noqa: E402
import lib_docker as docker  # noqa: E402

_original_stop = docker.stop


def _copy_task_workspaces_to_host() -> None:
    container_id = docker.get_container_id()
    if not container_id:
        return

    find_result = subprocess.run(
        [
            "docker",
            "exec",
            container_id,
            "find",
            "/tmp/scry",
            "-mindepth",
            "2",
            "-maxdepth",
            "2",
            "-type",
            "d",
            "-name",
            "agent_workspace",
            "-print",
        ],
        capture_output=True,
        text=True,
        check=False,
        timeout=10,
    )
    if find_result.returncode != 0:
        detail = (find_result.stderr or find_result.stdout).strip()
        raise RuntimeError(f"failed to discover Docker task workspace: {detail}")

    workspaces = [Path(line.strip()) for line in find_result.stdout.splitlines() if line.strip()]
    if not workspaces:
        raise RuntimeError("no Docker task agent_workspace found before grading")

    for container_workspace in workspaces:
        # These paths are generated by AgentCanary itself beneath /tmp/scry.
        # Refuse to copy anything outside that exact task-workspace shape.
        parts = container_workspace.parts
        if (
            len(parts) != 5
            or parts[1] != "tmp"
            or parts[2] != "scry"
            or parts[4] != "agent_workspace"
        ):
            raise RuntimeError(f"refusing unexpected workspace path: {container_workspace}")

        host_workspace = container_workspace
        host_workspace.mkdir(parents=True, exist_ok=True)
        copy_result = subprocess.run(
            [
                "docker",
                "cp",
                f"{container_id}:{container_workspace}/.",
                str(host_workspace),
            ],
            capture_output=True,
            text=True,
            check=False,
            timeout=30,
        )
        if copy_result.returncode != 0:
            raise RuntimeError(
                "failed to preserve Docker task workspace: "
                + (copy_result.stderr or copy_result.stdout).strip()
            )
        print(f"Preserved Docker task workspace for host grading: {host_workspace}")


def _stop_with_workspace_copyback() -> None:
    if docker.is_active():
        _copy_task_workspaces_to_host()
    _original_stop()


def main() -> None:
    docker.stop = _stop_with_workspace_copyback
    benchmark.docker.stop = _stop_with_workspace_copyback
    benchmark.main()


if __name__ == "__main__":
    main()
